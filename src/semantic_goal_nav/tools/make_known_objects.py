#!/usr/bin/env python3
"""Write config/known_objects.yaml from the objects placed in the Gazebo world file.

    python3 tools/make_known_objects.py ../aws-robomaker-small-house-world/worlds/small_house.world \
        config/known_objects.yaml

These are the true positions of the furniture in the simulated house. The semantic map
manager loads them (use_known_objects:=true) so the robot can go to an object it has not
seen yet; detections then refine them. Set use_known_objects:=false to build the map from
the camera only.
"""
import re
import sys

# Gazebo model name prefix -> semantic class
CLASSES = {
    'Bed_01': 'bed', 'NightStand_01': 'nightstand', 'ChairA_01': 'chair', 'ChairD_01': 'chair',
    'CoffeeTable_01': 'coffee table', 'KitchenTable_01': 'dining table', 'BalconyTable_01': 'dining table',
    'ReadingDesk_01': 'desk', 'Door_01': 'door', 'Dumbbell_01': 'dumbbell',
    'Refrigerator_01': 'refrigerator', 'SofaC_01': 'couch', 'Trash_01': 'trash can',
    'TV_01': 'tv', 'TV_02': 'tv', 'TVCabinet_01': 'cabinet', 'KitchenCabinet_01': 'cabinet',
    'Wardrobe_01': 'wardrobe', 'ShoeRack_01': 'shelf', 'Ball_01': 'sports ball',
}


def main(world, out):
    s = open(world).read()
    lines = ['# Generated by tools/make_known_objects.py from small_house.world (map frame = world frame).',
             '# True furniture positions in the simulated house; detections refine them.', 'objects:']
    for name, body in re.findall(r"<model name='([^']+)'>(.*?)</model>", s, re.S):
        key = re.sub(r'_\d{3}$', '', name)
        cls = CLASSES.get(key)
        pose = re.search(r'<pose[^>]*>([^<]+)</pose>', body)
        if not cls or not pose:
            continue
        x, y = (float(v) for v in pose.group(1).split()[:2])
        lines.append(f'  - {{class: {cls}, x: {x:.3f}, y: {y:.3f}, name: {name}}}')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(f'{len(lines) - 3} objects -> {out}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
